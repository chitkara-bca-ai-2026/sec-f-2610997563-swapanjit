import math
num=int(input("Enter a number:"))
expo=int(input("Enter an exponent: "))
decimal=float(input("Enter a decimal measurement: "))
power=math.pow(num,expo)
sqrt=math.sqrt(num)
ceil=math.ceil(decimal)
floor=math.floor(decimal)
print("----Results----")
print(f"Value             : {num:.1f}")
print(f"Exponent          : {expo:.1f}")
print(f"Power(pow)        : {power:.1f}")
print(f"Square Root (sqrt): {sqrt:.4f}")
print(f"Decimal value     : {decimal}")
print(f"Ceil value        : {ceil}")
print(f"Floor value       : {floor}")
